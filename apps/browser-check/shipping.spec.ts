import { test, expect } from '@playwright/test';
const url = process.env.SHIPPING_URL ?? 'http://shipping-api:8000';
test('shipping employee: multiline fulfilment, queues, packing, confirmed delivery and mobile detail', async ({ page, request }) => {
  const headers = { Authorization: 'Basic ' + Buffer.from(process.env.SHIPPING_USERNAME + ':' + process.env.SHIPPING_PASSWORD).toString('base64') };
  const status = await (await request.get(url + '/api/status', { headers })).json();
  expect((await request.post(url + '/api/control/reset', { headers, data: { confirm_run_id: status.run.id } })).ok()).toBe(true);
  expect((await request.post(url + '/api/control/speed', { headers, data: { speed: 20 } })).ok()).toBe(true);
  await page.goto(url);
  await page.getByLabel('Username', { exact: true }).fill('employee');
  await page.getByLabel('Password', { exact: true }).fill(process.env.SHIPPING_EMPLOYEE_PASSWORD!);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: /hold|resume|finaliz|reset|audit/i })).toHaveCount(0);
  const customer = 'Browser multiline ' + Date.now();
  const form = page.locator('.order-form');
  await form.getByLabel('Customer reference').fill(customer);
  await form.getByLabel('Destination', { exact: true }).fill('CUSTOMER-A');
  await form.locator('[name="sku-0"]').fill('PRODUCT');
  await form.locator('[name="quantity-0"]').fill('4');
  await form.getByRole('button', { name: 'Add line', exact: true }).click();
  await form.locator('[name="sku-1"]').fill('COMPONENT');
  await form.locator('[name="quantity-1"]').fill('3');
  await form.getByRole('button', { name: 'Create order', exact: true }).click();
  await page.getByLabel('Search orders').fill(customer);
  const row = page.locator('.order-desk tbody tr').filter({ hasText: customer });
  await expect(row).toHaveCount(1);
  await row.getByRole('button', { name: 'Request fulfilment', exact: true }).click();
  await page.getByRole('combobox', { name: 'Queue', exact: true }).selectOption('packing');
  await expect(row).toContainText('7 / 7 item');
  await row.getByRole('button', { name: 'Pack', exact: true }).click();
  await page.getByRole('combobox', { name: 'Queue', exact: true }).selectOption('dispatch');
  await row.getByRole('button', { name: 'Dispatch', exact: true }).click();
  await page.getByRole('combobox', { name: 'Queue', exact: true }).selectOption('all');
  await expect(row.locator('td').nth(3)).toHaveText('delivered');
  await row.getByRole('button', { name: /^[a-f0-9-]{36}$/ }).click();
  const detail = page.getByRole('region', { name: 'Order detail' });
  await expect(detail).toContainText('Record history');
  await expect(detail).toContainText('COMPONENT');
  await expect(detail).toContainText('PRODUCT');
  await expect(detail).toContainText('shortage');
  await expect(detail).toContainText('departed');
  await expect(detail).toContainText('delivered');
  await expect(detail).not.toContainText('Awaiting carrier confirmation');
  await page.screenshot({ path: '/artifacts/shipping-v1-employee-desktop.png', fullPage: true });
  await page.getByLabel('Search orders').fill('no-such-customer');
  await expect(page.getByText('No orders match this queue.', { exact: true })).toBeVisible();
  await page.getByLabel('Search orders').fill(customer);
  await expect(row).toHaveCount(1);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth + 1)).toBe(true);
  await page.screenshot({ path: '/artifacts/shipping-v1-employee-mobile.png', fullPage: true });
});

test('shipping employee: signed Livewire snapshot replay survives a lost response', async ({ page }) => {
  const headers = { Authorization: 'Basic ' + Buffer.from(process.env.SHIPPING_USERNAME + ':' + process.env.SHIPPING_PASSWORD).toString('base64') };
  const status = await (await page.request.get(url + '/api/status', { headers })).json();
  expect((await page.request.post(url + '/api/control/reset', { headers, data: { confirm_run_id: status.run.id } })).ok()).toBe(true);
  expect((await page.request.post(url + '/api/control/speed', { headers, data: { speed: 20 } })).ok()).toBe(true);
  await page.goto(url);
  await page.getByLabel('Username', { exact: true }).fill('employee');
  await page.getByLabel('Password', { exact: true }).fill(process.env.SHIPPING_EMPLOYEE_PASSWORD!);
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  const snapshot = await page.locator('.order-desk').getAttribute('wire:snapshot');
  const token = await page.locator('meta[name="csrf-token"]').getAttribute('content');
  const updateURI = await page.locator('script[data-update-uri]').getAttribute('data-update-uri');
  expect(snapshot).toBeTruthy();
  expect(token).toBeTruthy();
  expect(updateURI).toBeTruthy();
  const customer = 'Lost response ' + Date.now();
  const body = JSON.stringify({ _token: token, components: [{ snapshot, updates: { customer, destination: 'CUSTOMER-A', lines: [{ sku: 'PRODUCT', quantity: '1' }] }, calls: [{ path: '', method: 'createOrder', params: [] }] }] });
  const options = { headers: { 'X-Livewire': '1', 'X-CSRF-TOKEN': token!, 'Content-Type': 'application/json' }, data: body };
  const first = await page.request.post(new URL(updateURI!, url).href, options);
  expect(first.status()).toBe(200);
  // Simulate loss of the first response: retain the original signed snapshot
  // and exact request bytes while the command passes its simulation due time.
  let commandID = '';
  await expect.poll(async () => {
    const snapshot = await (await page.request.get(url + '/api/shipping', { headers })).json();
    const commands = snapshot.commands.filter((command: { id: string; body: { customer?: string }; outcome: string }) => command.body.customer === customer);
    if (commands.length === 1 && commands[0].outcome === 'completed') commandID = commands[0].id;
    return commandID;
  }).not.toBe('');
  const second = await page.request.post(new URL(updateURI!, url).href, options);
  expect(second.status()).toBe(200);
  const replay = await second.json();
  expect(replay.components[0].effects.html).toContain(commandID);
  const after = await (await page.request.get(url + '/api/shipping', { headers })).json();
  expect(after.commands.filter((command: { body: { customer?: string } }) => command.body.customer === customer).map((command: { id: string }) => command.id)).toEqual([commandID]);
  expect(after.orders.filter((order: { customer: string }) => order.customer === customer)).toHaveLength(1);
});
